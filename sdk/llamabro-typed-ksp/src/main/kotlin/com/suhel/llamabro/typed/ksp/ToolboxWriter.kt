package com.suhel.llamabro.typed.ksp

/**
 * Writes a toolbox's `X_LbToolbox.kt`: `fun X.asToolbox(json): Toolbox` over llamabro-typed's `tool(…)`, and an
 * arguments class per tool declared with separate parameters. Every name is fully qualified, so the file needs no
 * imports and can't clash with the app's.
 */
internal class ToolboxWriter(
    private val packageName: String,
    /** The toolbox's type as source, `app.Outer.Tools`. */
    private val receiver: String,
    /** The toolbox's class names joined with `_`, `Outer_Tools`: the file's and the arguments classes' stem. */
    private val stem: String,
    private val visibility: String,
    private val prefix: String,
) {
    private val out = StringBuilder()

    fun write(tools: List<ToolSpec>): String {
        val argsClasses = argsClassNames(tools)
        line("// Generated by llamabro-typed-ksp from $receiver. Do not edit.")
        if (packageName.isNotEmpty()) line("package ${qualified(packageName)}")
        line()
        line("/** The `@LbTool` methods of [$receiver] as a toolbox; [json] reads arguments and writes results. */")
        line("$visibility fun $receiver.asToolbox(json: $JSON = $JSON): $TYPED.Toolbox {")
        // generated code should add no warnings, for apps that build with warnings as errors
        if (tools.isNotEmpty()) line("    val box = this")
        line("    return $TYPED.toolboxOf(")
        tools.forEach { tool(it, argsClasses[it]) }
        line("    )")
        line("}")
        tools.forEach { tool -> (tool.args as? ToolArgs.Fields)?.let { argsClass(argsClasses.getValue(tool), it) } }
        return out.toString()
    }

    private fun tool(tool: ToolSpec, argsClass: String?) {
        val args = (tool.args as? ToolArgs.Whole)?.type ?: argsClass
        val call = "box.${id(tool.function.simpleName.asString())}(${tool.call.joinToString(", ")})"
        // a method that doesn't suspend may block, so it leaves the loop's thread (D62)
        val body = if (tool.suspending) call else "kotlinx.coroutines.withContext($IO) { $call }"
        val param = if (tool.call.any { it.startsWith("args") }) "args" else "_"
        line("        $TYPED.tool<$args, ${tool.result}>(")
        line("            ${literal(prefix + tool.name)},")
        line("            ${literal(tool.description)},")
        line("            requiresApproval = ${tool.requiresApproval},")
        line("            json = json,")
        line("        ) { $param -> $body },")
    }

    private fun argsClass(name: String, args: ToolArgs.Fields) {
        line()
        line("@kotlinx.serialization.Serializable")
        line("private class $name(")
        args.fields.forEach { field ->
            val text = literal(field.description)
            val description = if (field.description.isEmpty()) "" else "@$LB_DESCRIPTION($text) "
            val default = if (field.optional) " = null" else ""
            line("    ${description}val ${id(field.name)}: ${field.type}$default,")
        }
        line(")")
    }

    /** `Tools_LbArgs_forecast` per tool with separate parameters; tool names are unique, `-` aside. */
    private fun argsClassNames(tools: List<ToolSpec>): Map<ToolSpec, String> {
        val taken = mutableSetOf<String>()
        return tools.filter { it.args is ToolArgs.Fields }.associateWith { tool ->
            val base = "${stem}_LbArgs_${tool.name.replace('-', '_')}"
            generateSequence(1) { it + 1 }.map { if (it == 1) base else "$base$it" }.first(taken::add)
        }
    }

    private fun line(text: String = "") {
        out.append(text).append('\n')
    }

    private companion object {
        const val JSON = "kotlinx.serialization.json.Json"
        const val IO = "kotlinx.coroutines.Dispatchers.IO"
    }
}
